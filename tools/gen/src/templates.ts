// Embeds packages/documents/templates/*.xlsx into packages/documents/src/templates.generated.ts as base64, so the
// document builders need no filesystem (C12, SPEC-12 §4.1). A test fails when the committed file is stale; the file
// is not formatted (vite.config.ts).
// Usage: node tools/gen/src/templates.ts (from the repo root), or `pnpm gen:templates`.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

export const TEMPLATES_DIR = "packages/documents/templates";
export const OUTPUT = "packages/documents/src/templates.generated.ts";

export interface TemplateFile {
  file: string;
  bytes: Uint8Array;
}

/** The generated module: one base64 string per template, keyed by file name without `.xlsx`. */
export function renderTemplates(files: readonly TemplateFile[]): string {
  const entries = [...files]
    .sort((a, b) => a.file.localeCompare(b.file))
    .map(({ file, bytes }) => `  ${file.slice(0, -".xlsx".length)}: "${Buffer.from(bytes).toString("base64")}",`);
  return [
    `// Generated by tools/gen/src/templates.ts from ${TEMPLATES_DIR}/*.xlsx. Do not edit.`,
    "export const TEMPLATES_BASE64 = {",
    ...entries,
    "} as const;",
    "",
  ].join("\n");
}

export function readTemplateFiles(): TemplateFile[] {
  return readdirSync(TEMPLATES_DIR)
    .filter((file) => file.endsWith(".xlsx"))
    .map((file) => ({ file, bytes: readFileSync(join(TEMPLATES_DIR, file)) }));
}

if (import.meta.main) writeFileSync(OUTPUT, renderTemplates(readTemplateFiles()));
