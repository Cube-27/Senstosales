// Embeds packages/db/migrations/NNNN_<name>.sql into packages/db/src/migrations.generated.ts, so the migrator needs
// no filesystem (C12) and the sidecar carries its migrations (SPEC-05 §9). Statements are split at drizzle-kit's
// breakpoints. A test fails when the committed file is stale; the file is not formatted (vite.config.ts).
// Usage: node tools/gen/src/migrations.ts (from the repo root)
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

export const MIGRATIONS_DIR = "packages/db/migrations";
export const OUTPUT = "packages/db/src/migrations.generated.ts";

const FILE = /^(\d{4})_(\w+)\.sql$/;
export const BREAKPOINT = "--> statement-breakpoint";

export interface MigrationFile {
  file: string;
  sql: string;
}

function render(version: number, name: string, sql: string): string {
  const statements = sql
    .split(BREAKPOINT)
    .map((s) => s.trim())
    .filter((s) => s !== "");
  return [
    "  {",
    `    version: ${version},`,
    `    name: ${JSON.stringify(name)},`,
    "    statements: [",
    ...statements.map((s) => `      ${JSON.stringify(s)},`),
    "    ],",
    "  },",
  ].join("\n");
}

/** The generated module for these files, in version order; versions must run 1, 2, 3 … without gaps. */
export function renderMigrations(files: readonly MigrationFile[]): string {
  const sorted = [...files].sort((a, b) => a.file.localeCompare(b.file));
  const migrations = sorted.map(({ file, sql }, i) => {
    const [, version, name] = FILE.exec(file) ?? [];
    if (Number(version) !== i + 1 || name === undefined) throw new Error(`${file}: expected version ${i + 1}`);
    return render(Number(version), name, sql);
  });
  return [
    `// Generated by tools/gen/src/migrations.ts from ${MIGRATIONS_DIR}/*.sql. Do not edit.`,
    'import type { Migration } from "./migrator.ts";',
    "",
    "export const MIGRATIONS: readonly [Migration, ...Migration[]] = [",
    ...migrations,
    "];",
    "",
  ].join("\n");
}

export function readMigrationFiles(dir = MIGRATIONS_DIR): MigrationFile[] {
  return readdirSync(dir)
    .filter((file) => file.endsWith(".sql"))
    .map((file) => ({ file, sql: readFileSync(join(dir, file), "utf8") }));
}

if (import.meta.main) writeFileSync(OUTPUT, renderMigrations(readMigrationFiles()));
